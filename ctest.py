"""ctest.py — a small C-test (after Hernandez-Orallo, 1998), in pure Python.

Companion to 'What Is Intelligence?' stage 3b.
Items are letter sequences; the task is to give the next letter.
Each item is generated by a program in a tiny language, and its
difficulty is the Kt complexity of the SHORTEST program that produces
the shown letters:  Kt = length in bits + log2(steps to run it).
An item is kept only if it is "unquestionable": every program within
MARGIN bits of the shortest one agrees on the next letter.

The language (letters are 0..25 = a..z, arithmetic mod 26):
  Seq(s, k)       s, s+k, s+2k, ...                       11 bits
  Acc(s, k, d)    steps grow by d:  s, s+k, s+2k+d, ...    15 bits
  Inter(P, Q)     interleave two Seq/Acc programs          2 + |P| + |Q|
  Rep(P, r)       each letter of P repeated r times        6 + |P|
"""
import math, random

A = "abcdefghijklmnopqrstuvwxyz"
SHOW, MARGIN = 7, 2.0

def gen_seq(s, k):
    i = 0
    while True:
        yield (s + i * k) % 26, 1
        i += 1

def gen_acc(s, k, d):
    v, step = s, k
    while True:
        yield v % 26, 1
        v += step
        step += d

def gen_inter(p, q):
    a, b = p(), q()
    while True:
        x, c1 = next(a); yield x, c1 + 1
        y, c2 = next(b); yield y, c2 + 1

def gen_rep(p, r):
    g = p()
    while True:
        x, c = next(g)
        for j in range(r):
            yield x, (c if j == 0 else 0) + 1

def run(prog, n):
    g, out, steps = prog(), [], 0
    for _ in range(n):
        x, c = next(g)
        out.append(x); steps += c
    return tuple(out), steps

def programs():
    """Yield (name, length_bits, thunk) for every program in the language."""
    seqs = [("Seq(%s,%+d)" % (A[s], k), 11, (lambda s=s, k=k: gen_seq(s, k)))
            for s in range(26) for k in range(-3, 6)]
    accs = [("Acc(%s,%+d,%d)" % (A[s], k, d), 15, (lambda s=s, k=k, d=d: gen_acc(s, k, d)))
            for s in range(26) for k in range(-2, 4) for d in (1, 2, 3)]
    base = seqs + accs
    inters = [("Inter(%s,%s)" % (n1, n2), 2 + l1 + l2,
               (lambda g1=g1, g2=g2: gen_inter(g1, g2)))
              for (n1, l1, g1) in seqs for (n2, l2, g2) in base]
    for p in base + inters:
        yield p
    for (n, l, g) in base + inters[::7]:          # thin the nested ones for speed
        for r in (2, 3):
            yield ("Rep(%s,%d)" % (n, r), 6 + l, (lambda g=g, r=r: gen_rep(g, r)))

# ---- build the item bank ----
runs = []   # (Kt, first SHOW+1 letters, program name)
for name, length, g in programs():
    seq, steps = run(g, SHOW + 1)
    runs.append((length + math.log2(steps), seq, name))

def build(show):
    bank = {}   # shown prefix -> list of (Kt, next letter, program name)
    for kt, seq, name in runs:
        bank.setdefault(seq[:show], []).append((kt, seq[show], name))
    items = []
    for prefix, progs in bank.items():
        progs.sort()
        best_kt, answer, name = progs[0]
        if all(nxt == answer for kt, nxt, _ in progs if kt <= best_kt + MARGIN):
            items.append((best_kt, prefix, answer, name))
    return bank, items

for show in (3, 4, 5, SHOW):
    b, it = build(show)
    print("show %d letters: %6d distinct sequences, %5.1f%% unquestionable" %
          (show, len(b), 100 * len(it) / len(b)))
bank, items = build(SHOW)

bands = [(0, 16), (16, 22), (22, 28), (28, 34), (34, 99)]
rng = random.Random(7)
test = []
for lo, hi in bands:
    pool = [it for it in items if lo <= it[0] < hi]
    test += [(lo, hi, it) for it in rng.sample(pool, min(20, len(pool)))]

# ---- test-takers ----
def wrap(d):  # a difference mod 26 as a signed step
    d %= 26
    return d - 26 if d > 13 else d

def constant_step(x):
    return (x[-1] + wrap(x[-1] - x[-2])) % 26

def lookup(x):
    for i in range(len(x) - 2, -1, -1):
        if x[i] == x[-1]:
            return x[i + 1]
    return constant_step(x)

def difference_table(x):
    """A different 'language': repeated differences until constant (up to 3 levels)."""
    rows = [list(x)]
    for _ in range(3):
        r = rows[-1]
        rows.append([wrap(r[i + 1] - r[i]) for i in range(len(r) - 1)])
        if len(set(rows[-1])) == 1:
            nxt = rows[-1][-1]
            for r in reversed(rows[:-1]):
                nxt = r[-1] + nxt
            return nxt % 26
    return constant_step(x)

def test_makers_language(x):
    progs = bank.get(tuple(x))
    return min(progs)[1] if progs else constant_step(x)

takers = [("constant step", constant_step), ("lookup", lookup),
          ("difference table", difference_table), ("test-maker's language", test_makers_language)]

print("\nsample items (shortest program, Kt in bits):")
seen = set()
for lo, hi, (kt, prefix, ans, name) in test:
    if (lo, hi) in seen: continue
    seen.add((lo, hi))
    print("  %-9s ?  -> %s   Kt %5.1f   %s" % ("".join(A[c] for c in prefix), A[ans], kt, name))

print("\nscores (fraction correct) by difficulty band:")
print("  %-22s" % "Kt band" + "".join("%9s" % ("%d-%d" % b) for b in bands))
for tname, f in takers:
    row = []
    for lo, hi in bands:
        band = [it for l, h, it in test if (l, h) == (lo, hi)]
        row.append(sum(f(list(p)) == a for _, p, a, _ in band) / len(band))
    print("  %-22s" % tname + "".join("%9.2f" % v for v in row))